(function () {
  "use strict";
  var doc = document.body.dataset.doc; // consent | privacy
  var q = new URLSearchParams(location.search).get("a");
  var slug = q ? q.toLowerCase().replace(/[^a-z0-9-]/g, "") || "demo" : "demo";

  function esc(s) { return String(s == null ? "" : s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; }); }

  function getJson(url) { return fetch(url, { cache: "no-store" }).then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); }); }
  getJson("api/agency.php?a=" + encodeURIComponent(slug))
    .catch(function () { return getJson("agencies/" + slug + ".json"); })
    .then(function (cfg) {
      var L = cfg.legal || {};
      var op = esc(L.operator || cfg.name);
      var inn = L.inn ? ", ИНН " + esc(L.inn) : "";
      var ogrn = L.ogrn ? ", " + esc(L.ogrn) : "";
      var addr = L.address ? ", адрес: " + esc(L.address) : "";
      var mail = esc(L.email || "");
      var phone = esc(cfg.phone || "");
      var updated = esc(L.updated || "");
      var back = "zapis.html?a=" + encodeURIComponent(slug);
      var processor = esc(L.processor || "");
      document.getElementById("back").href = back;
      if (cfg.demo) document.getElementById("demoNote").hidden = false;

      var data = "<ul><li>имя;</li><li>номер телефона;</li><li>адрес, по которому нужен визит;</li><li>имя и возраст ребёнка, если вы их указали;</li><li>пожелания к празднику, которые вы написали в заявке;</li><li>выбранные дата, время, программа и стоимость заказа.</li></ul>";
      var html;

      if (doc === "consent") {
        document.title = "Согласие на обработку персональных данных — " + cfg.name;
        html =
          "<h1>Согласие на обработку персональных данных</h1>" +
          "<p>Отмечая галочку в форме заказа на сайте, я свободно, своей волей и в своём интересе даю согласие " + op + inn + ogrn + addr + " (далее — Оператор) на обработку моих персональных данных на следующих условиях.</p>" +
          "<h2>Какие данные</h2>" + data +
          "<p>Если я указываю данные ребёнка, я подтверждаю, что являюсь его законным представителем и даю согласие на обработку этих данных от его имени.</p>" +
          "<h2>Зачем</h2><p>Чтобы оформить и выполнить мой заказ: связаться со мной для подтверждения, согласовать детали, организовать визит артистов по указанному адресу.</p>" +
          "<h2>Что Оператор может делать с данными</h2><p>Сбор, запись, систематизация, накопление, хранение, уточнение, использование, передача артистам, которые выполняют заказ, обезличивание, блокирование, удаление и уничтожение. Обработка ведётся с использованием средств автоматизации и без них.</p>" +
          (processor ? "<p>Я согласен, что работу сервиса онлайн-записи и хранение заявки по поручению Оператора обеспечивает " + processor + ".</p>" : "") +
          "<h2>Сколько действует</h2><p>Согласие действует до выполнения заказа и затем ещё " + esc(L.keepMonths || 12) + " месяцев, если раньше я его не отзову.</p>" +
          "<h2>Как отозвать</h2><p>Я могу отозвать согласие в любой момент, написав Оператору" + (mail ? " на " + mail : "") + (phone ? " или позвонив по номеру " + phone : "") + ". После отзыва Оператор прекращает обработку и удаляет данные в течение 10 рабочих дней, кроме случаев, когда хранить их обязывает закон.</p>" +
          "<p>Как Оператор обращается с данными, подробно описано в <a href=\"" + (/^https:\/\//.test(L.policyUrl || "") ? esc(L.policyUrl) : "privacy.html?a=" + encodeURIComponent(slug)) + "\">политике обработки персональных данных</a>.</p>";
      } else {
        document.title = "Политика обработки персональных данных — " + cfg.name;
        html =
          "<h1>Политика обработки персональных данных</h1>" +
          (updated ? "<p class=\"meta\">Редакция от " + updated + "</p>" : "") +
          "<h2>1. Кто обрабатывает данные</h2><p>Оператор персональных данных — " + op + inn + ogrn + addr + ". Связаться по вопросам данных можно" + (mail ? " по почте " + mail : "") + (phone ? (mail ? " или" : "") + " по телефону " + phone : "") + ".</p>" +
          "<h2>2. Какие данные мы получаем</h2><p>Только то, что вы сами указываете в форме заказа:</p>" + data +
          "<p>Мы не собираем паспортные данные и не принимаем оплату на этой странице.</p>" +
          "<h2>3. Зачем</h2><p>Для оформления и выполнения заказа: подтвердить визит, согласовать детали и приехать по адресу. Мы не используем данные для рассылок и не продаём их.</p>" +
          "<h2>4. Основание</h2><p>Ваше согласие, которое вы даёте отдельной галочкой в форме заказа (<a href=\"consent.html" + (q ? "?a=" + encodeURIComponent(slug) : "") + "\">текст согласия</a>), и исполнение договора, стороной которого вы являетесь.</p>" +
          "<h2>5. Кому передаём</h2><p>Артистам и сотрудникам Оператора, которые выполняют ваш заказ, — только то, что им нужно для визита. Другим лицам данные передаются только в случаях, предусмотренных законом.</p>" +
          (processor ? "<p>Работу сервиса онлайн-записи и хранение заявок по поручению Оператора обеспечивает " + processor + ". Он обрабатывает данные только для работы сервиса, соблюдает их конфиденциальность и принимает меры по их защите в соответствии со статьёй 19 Федерального закона № 152-ФЗ.</p>" : "") +
          "<h2>6. Как храним</h2><p>Данные хранятся на сервере в России, доступ к ним есть только у сотрудников Оператора. Мы храним данные до выполнения заказа и ещё " + esc(L.keepMonths || 12) + " месяцев, затем удаляем.</p>" +
          "<h2>7. Ваши права</h2><p>Вы можете узнать, какие ваши данные у нас есть, попросить их исправить или удалить, а также отозвать согласие. Для этого напишите или позвоните нам по контактам из раздела 1. Мы ответим в течение 10 рабочих дней.</p>" +
          "<h2>8. Изменения</h2><p>Мы можем обновлять эту политику. Действующая редакция всегда опубликована на этой странице.</p>";
      }
      document.getElementById("doc").innerHTML = html;
    })
    .catch(function () {
      document.getElementById("doc").innerHTML = "<h1>Документ не найден</h1><p>Проверьте ссылку.</p>";
    });
})();
